// Disposable authenticated draft and synthetic recording browser proof; no model is used.
import { createRequire } from 'node:module';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(require.resolve('playwright', { paths: [process.env.PLAYWRIGHT_NODE_MODULES] }));
const base = process.env.ATHENA_QA_BASE;
const session = fs.readFileSync(process.env.ATHENA_QA_SESSION_FILE, 'utf8').trim();
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
try {
  await context.addCookies([{ name: 'sessionid', value: session, url: base }]);
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base + '/operations');
  await page.getByText('No drafts yet.').waitFor();
  await page.locator('#draft-name').fill('Shop entrance');
  await page.locator('#draft-save').click();
  await page.getByText('Saved draft. Changes are saved when you select Save draft.').waitFor();
  await page.reload();
  const item = page.locator('#draft-list').getByRole('button', { name: 'Shop entrance' });
  await item.click();
  await page.waitForFunction(() => document.querySelector('#draft-name').value === 'Shop entrance');
  assert.equal(await page.locator('#draft-name').inputValue(), 'Shop entrance');
  await page.locator('#recording-file').setInputFiles(process.env.ATHENA_QA_VIDEO);
  await page.locator('#recording-upload').click();
  await page.getByText('Recording saved. Counting is not available yet.').waitFor();
  await page.waitForFunction(() => document.querySelector('#recording-preview').readyState >= 2);
  assert.equal(await page.locator('#recording-preview').evaluate(v => v.videoWidth), 64);
  await page.locator('#recording-preview').evaluate(v => v.play());
  await page.waitForFunction(() => document.querySelector('#recording-preview').currentTime > .1);
  await page.locator('#recording-preview').evaluate(v => v.pause());
  await page.locator('#line-positive').fill('Entering');
  await page.locator('#line-save').click();
  await page.getByText('Choose both line points before naming directions.').waitFor();
  await page.locator('#line-canvas').scrollIntoViewIfNeeded();
  const box = await page.locator('#line-canvas').boundingBox();
  await page.mouse.click(box.x + box.width * .2, box.y + box.height * .5);
  await page.mouse.click(box.x + box.width * .8, box.y + box.height * .5);
  const arrowTip = await page.locator('#line-canvas').evaluate(canvas => Array.from(canvas.getContext('2d').getImageData(32, 28, 1, 1).data));
  assert.ok(arrowTip[0] > 200 && arrowTip[1] > 200 && arrowTip[2] > 200, 'positive-side arrow must point down for a left-to-right horizontal line');
  await page.locator('#line-positive').fill('Entering');
  await page.locator('#line-negative').fill('Leaving');
  const savedLine = page.waitForResponse(response => response.url().includes('/api/operation-drafts/') && response.request().method() === 'PUT');
  await page.locator('#line-save').click();
  assert.equal((await savedLine).status(), 200);
  await page.waitForTimeout(250);
  const lineSaveStatus = await page.locator('#line-status').innerText();
  assert.match(lineSaveStatus, /Saved line/, `Expected saved line status, received: ${lineSaveStatus}`);
  const video = page.locator('#recording-preview');
  await video.evaluate(v => { v.currentTime = .25; });
  await page.waitForFunction(() => Math.abs(document.querySelector('#recording-preview').currentTime - .25) < .05);
  await page.locator('#mark-positive-event').click();
  await video.evaluate(v => { v.currentTime = .75; });
  await page.waitForFunction(() => Math.abs(document.querySelector('#recording-preview').currentTime - .75) < .05);
  await page.locator('#mark-negative-event').click();
  assert.equal(await page.locator('#reference-event-list li').count(), 2);
  const savedReferences = page.waitForResponse(response => response.url().includes('/api/operation-drafts/') && response.request().method() === 'PUT');
  await page.locator('#line-save').click();
  assert.equal((await savedReferences).status(), 200);
  await page.reload();
  await page.locator('#draft-list').getByRole('button', { name: 'Shop entrance' }).click();
  await page.waitForFunction(() => document.querySelector('#recording-preview').readyState >= 2);
  assert.match(await page.locator('#recording-info').innerText(), /64 × 48/);
  assert.ok(Math.abs(Number(await page.locator('#line-start-x').inputValue()) - 20) < .2);
  assert.ok(Math.abs(Number(await page.locator('#line-end-x').inputValue()) - 80) < .2);
  assert.equal(await page.locator('#line-positive').inputValue(), 'Entering');
  assert.equal(await page.locator('#line-negative').inputValue(), 'Leaving');
  assert.equal(await page.locator('#reference-event-list li').count(), 2);
  assert.match(await page.locator('#reference-event-list').innerText(), /0\.25\d s · Entering/);
  assert.match(await page.locator('#reference-event-list').innerText(), /0\.75\d s · Leaving/);
  await page.locator('#line-start-x').fill('19');
  const changedGeometry = page.waitForResponse(response => response.url().includes('/api/operation-drafts/') && response.request().method() === 'PUT');
  await page.locator('#line-save').click();
  assert.equal((await changedGeometry).status(), 200);
  await page.getByText('Line changed; the old reference crossings were cleared. Mark them again against the saved line.').waitFor();
  assert.equal(await page.locator('#reference-event-list li').count(), 0);
  await page.locator('#recording-delete').click();
  await page.getByRole('alertdialog').getByRole('button', { name: 'Remove recording' }).click();
  await page.getByText(/Removed from this draft/).waitFor();
  await page.locator('#recording-file').setInputFiles(process.env.ATHENA_QA_VIDEO);
  await page.locator('#recording-upload').click();
  await page.getByText('Recording saved. Counting is not available yet.').waitFor();
  assert.equal(await page.locator('#line-start-x').inputValue(), '', 'removing a recording must clear its old line');
  assert.equal(await page.locator('#reference-event-list li').count(), 0, 'removing a recording must clear its old reference crossings');
  await page.locator('#draft-name').fill('Main door');
  await page.locator('#draft-save').click();
  await page.locator('#draft-list').getByRole('button', { name: 'Main door' }).waitFor();
  // Another tab advances the real revision; a stale save must remain unsaved.
  const other = await context.newPage();
  await other.goto(base + '/operations');
  await other.locator('#draft-list').getByRole('button', { name: 'Main door' }).click();
  await other.waitForFunction(() => document.querySelector('#draft-name').value === 'Main door');
  await other.locator('#draft-name').fill('Changed elsewhere');
  await other.locator('#draft-save').click();
  await other.locator('#draft-list').getByRole('button', { name: 'Changed elsewhere' }).waitFor();
  await page.locator('#draft-name').fill('Unsaved local change');
  for (const [id, value] of [['line-start-x', '15'], ['line-start-y', '50'], ['line-end-x', '85'], ['line-end-y', '50'], ['line-positive', 'In'], ['line-negative', 'Out']]) {
    await page.locator(`#${id}`).fill(value);
  }
  await page.locator('#draft-save').click();
  await page.getByText('Not saved. Your changes are still here.').waitFor();
  assert.equal(await page.locator('#draft-name').inputValue(), 'Unsaved local change');
  assert.equal(await page.locator('#line-start-x').inputValue(), '15');
  assert.equal(await page.locator('#line-positive').inputValue(), 'In');
  assert.match(await page.locator('#draft-error').innerText(), /changed elsewhere/i);
  page.once('dialog', dialog => dialog.accept());
  await page.reload();
  await page.locator('#draft-list').getByRole('button', { name: 'Changed elsewhere' }).click();
  await page.waitForFunction(() => document.querySelector('#draft-name').value === 'Changed elsewhere');
  await page.locator('#draft-delete').click();
  await page.getByRole('alertdialog').getByRole('button', { name: 'Delete draft' }).click();
  await page.getByText('No drafts yet.').waitFor();
  await page.goto(base + '/');
  const homeLimits = await page.locator('[data-testid="photo-inspection-limits"]').innerText();
  assert.match(homeLimits, /not live monitoring or a complete count of arrivals and departures/i);
  assert.match(homeLimits, /six still frames/i);
  assert.match(homeLimits, /separate advanced workflow/i);
  await page.getByTestId('sidebar-menu-toggle').click();
  await page.getByTestId('sidebar-signout-button').click();
  await page.goto(base + '/');
  await page.getByTestId('landing-hero-title').waitFor();
  assert.match(await page.locator('.lp-lead').innerText(), /six still frames/i);
  assert.match(await page.locator('.lp-lead').innerText(), /not a complete crossing count or live monitor/i);
  assert.match(await page.locator('.lp-lead').innerText(), /separate advanced workflow/i);
  assert.match(await page.locator('[data-testid="landing-case-footfall"]').innerText(), /does not count every crossing or measure waiting time/i);
  assert.match(await page.locator('[data-testid="landing-case-parking"]').innerText(), /not live monitoring or a sensor-grade vacancy count/i);
  await page.getByTestId('landing-demo-tab-footfall').click();
  await page.waitForFunction(() => document.getElementById('demo-h').textContent.includes('A still picture cannot establish crossing totals.'));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);
  console.log('PASS: synthetic MP4 draft flow and capability wording across signed-in Home and public landing at 390px; no page errors or overflow.');
} finally {
  await context.close();
  await browser.close();
}
